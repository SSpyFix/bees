export function beeAbilities(bee: BeeDefinition, gifted = false) {
  return [...(SPECIES_ABILITIES[bee.face] ?? []), ...(gifted ? ["inspire"] : [])];
}
export function abilityNames(bee: BeeDefinition, gifted = false) {
  return beeAbilities(bee, gifted).map(id => abilityInfo(id).name).join(", ") || "None";
}
