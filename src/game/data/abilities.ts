export const abilityInfo = (kind: string): AbilityInfo =>
  ABILITIES[kind] ?? {
    name: kind.startsWith("field:") ? `${kind.slice(6)} Field Boost` : kind,
    color: "#ffe976",
    icon: "✿",
  };

